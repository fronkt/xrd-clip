"""Re-simulate the stick patterns of the disordered added library entries with their site occupancies (board review
11-19, A07; CIFs from scripts/52).

  PYTHONPATH=src python scripts/53_resim_disorder.py        -> cache/sticks_extra/shard_extra.npz (patched; the original
                                                               is kept as shard_extra.npz.pre_occ and is always the input)

The CSD Python API returns the asymmetric unit with occupancies but without the minor disorder components, so two
readings exist for each disordered entry: (A) the sites with their CSD occupancies, right for disorder generated by
symmetry (ZZZUWK: four orientations at 0.25 each), and (B) the major component at full occupancy, right when an explicit
minor component is missing. Both are simulated, and the one whose pattern agrees better with the CCDC's own powder
simulation of the entry (scripts/51 ccdc, which uses the full disorder model) is kept. Only the stick fields change; the
atom lists that the learned model encodes are left as they were (the encoder has no occupancy input). Writes
cache/real_extra/occ/resim.json with the variant chosen and both correlations.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import sys

import numpy as np

SHARD = "cache/sticks_extra/shard_extra.npz"
OCC = "cache/real_extra/occ"
FIELDS = ("two_theta", "intensity", "hkl", "d_hkl", "recip")


def main() -> int:
    from importlib import import_module
    from xrdclip.data.simulate import simulate_one
    sys.path.insert(0, "scripts")
    bench, xc = import_module("19_real_bench"), import_module("51_sim_crosscheck")
    index = json.load(open(f"{OCC}/index.json"))
    todo = sorted(k for k, v in index.items() if v.get("has_disorder") and v.get("n_partial", 0) > 0)
    if not os.path.exists(SHARD + ".pre_occ"):
        shutil.copy2(SHARD, SHARD + ".pre_occ")
    with np.load(SHARD + ".pre_occ", allow_pickle=True) as z:
        cols = {f: z[f].copy() for f in z.files}
    with np.load("cache/sim_check/ccdc.npz") as cc:
        ccdc = {str(r): y for r, y in zip(cc["refcode"], cc["y"])}
    rc = [str(x) for x in cols["refcode"]]
    report = {}
    for r in todo:
        if r not in rc:
            report[r] = {"status": "not in the library (no coordinates)"}
            continue
        i = rc.index(r)
        a = open(f"{OCC}/{r}.cif").read()
        lines = a.splitlines()
        k = next(j for j, ln in enumerate(lines) if ln.strip() == "_atom_site_occupancy")
        b = "\n".join(lines[:k + 1] + [re.sub(r" (0\.[5-9]\d*)$", " 1.0000", ln) for ln in lines[k + 1:]]) + "\n"
        cand = {}
        for name, txt in (("A_occupancies", a), ("B_major_component", b)):
            sim = simulate_one({"refcode": r, "cif": txt, "smiles": cols["smiles"][i], "cell": cols["cell"][i]})
            if sim is None:
                continue
            y = bench.render([{f: sim[f] for f in FIELDS}])[0]
            corr = float(np.corrcoef(xc.smooth(y), xc.smooth(ccdc[r]))[0, 1]) if r in ccdc else float("nan")
            cand[name] = (corr, sim)
        if not cand:
            report[r] = {"status": "simulation failed; kept"}
            continue
        best = max(cand, key=lambda n: (np.nan_to_num(cand[n][0], nan=-1.0), n == "A_occupancies"))
        sim = cand[best][1]
        report[r] = {"status": "patched", "variant": best, **{f"r_vs_ccdc_{n}": round(v[0], 4) for n, v in cand.items()},
                     "n_sticks_before": int(len(cols["two_theta"][i])), "n_sticks_after": int(len(sim["two_theta"]))}
        for f in FIELDS:
            cols[f][i] = np.asarray(sim[f], dtype=np.asarray(cols[f][i]).dtype)
    np.savez_compressed(SHARD, **cols)
    json.dump(report, open(f"{OCC}/resim.json", "w"), indent=1)
    n = sum(v["status"] == "patched" for v in report.values())
    print(f"[53] {len(todo)} entries with partial occupancies; {n} patched in {SHARD} "
          f"({sum(v.get('variant') == 'B_major_component' for v in report.values())} as the major component); "
          f"{sum('failed' in v['status'] for v in report.values())} failed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
